def hmix_from_fig1(t_C, xi, h_fig_kcal):
    """由图1 (T,ξ,h) 反推混合焓 [kJ/kg]：hmix = h_fig − [ξ·hR22 + (1−ξ)·hDMF]。"""
    h_ideal = xi * h_r22_borde1978(t_C) + (1.0 - xi) * h_dmf_borde1978(t_C)
    return (h_fig_kcal - h_ideal) * KCAL2KJ
